// Exercise both real web components and shadow DOM event propagation.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require(process.argv[2] || 'jsdom');
const fragment = name => fs.readFileSync(path.join(__dirname, '../_flow/types/editors', name + '.html'), 'utf8');
const dom = new JSDOM('<!doctype html>' + fragment('literal') + fragment('value'), { runScripts: 'dangerously' });
const { document, Event } = dom.window;
dom.window.HTMLElement.prototype.scrollIntoView = function () {};
const editor = document.createElement('flow-value-editor');
document.body.append(editor);
const events = [];
editor.addEventListener('flow-value', event => events.push(event.detail));
const context = { scopes: { input: { paths: [{ path: 'input.count', type: 'number' }] } } };
const state = (type, value, extra = {}) => editor.setState({ value, context,
  propertyDefinition: { kind: 'value', type, ...extra } });
const root = editor.shadowRoot;
const literal = root.querySelector('flow-literal-editor');
state('number', 12);
assert.equal(editor._mode, 'literal');
assert.equal(literal.shadowRoot.querySelector('[data-number]').value, '12');
assert.equal(root.querySelector('textarea[part="input"]').classList.contains('hidden'), true);
const number = literal.shadowRoot.querySelector('[data-number]');
number.value = '23';
number.dispatchEvent(new Event('input', { bubbles: true }));
assert.equal(editor.value, '23');
assert.equal(events.at(-1).value, '23');
state('boolean', false);
assert.equal(literal.shadowRoot.querySelector('[data-boolean] input').checked, false);
state('string', 'context', { enum: ['context', 'engine'] });
const select = literal.shadowRoot.querySelector('[data-select]');
assert.equal(select.options.length, 2);
select.value = 'engine';
select.dispatchEvent(new Event('change', { bubbles: true }));
assert.equal(editor.value, 'engine');
state('number', 0);
root.querySelector('[data-mode=simple]').click();
assert.equal(editor.value, '0', 'opening the expression tab must not erase the current value');
root.querySelector('[data-mode=literal]').click();
root.querySelector('[data-path="input.count"]').click();
assert.equal(editor._mode, 'simple');
assert.equal(editor.value, '{{ input.count }}');
const expression = root.querySelector('[data-simple=expression]');
assert.equal(expression.classList.contains('hidden'), false, 'expression must not be mistaken for the raw textarea');
assert.equal(expression.value, 'input.count');
expression.value = 'input.count + 1';
expression.dispatchEvent(new Event('input', { bubbles: true }));
assert.equal(editor.value, '{{ input.count + 1 }}');
root.querySelector('[data-mode=custom]').click();
const raw = root.querySelector('textarea[part="input"]');
assert.equal(raw.value, editor.value);
assert.equal(raw.classList.contains('hidden'), false);
raw.value = 'prefix {{ input.count }}';
raw.dispatchEvent(new Event('input', { bubbles: true }));
assert.equal(editor.value, raw.value);
state('string', 'prefix {{ input.count }}');
assert.equal(editor._mode, 'custom', 'mixed existing expressions must not be silently converted');
dom.window.close();
console.log('value-editor DOM: typed literals, enum, source picker, expression and raw roundtrip OK');
