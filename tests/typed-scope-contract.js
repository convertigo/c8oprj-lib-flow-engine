const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const load = name => vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../_flow/modules',name+'.js'),'utf8'));
const contract = load('typed-scope-contract'), schemas=load('schema-contract'), destinations=load('destination-contract'), scope=load('scope-path-utils');
let scopes={local:{},result:{},input:{}};
const env={scopeNames:['local','result','input'],destinationContract:destinations,assertNoRuntimeHandle:()=>{},raise:(code,message)=>{const e=new Error(message);e.code=code;throw e;}};
const read=path=>scope.readScopePath(scopes,path,env), write=(path,value)=>scope.writeScopePath(scopes,path,value,env);
const api=contract.create({schemas,destinations,scopes:()=>scopes,read,write,raise:env.raise});
const integer={type:'integer'}, items={type:'array',items:integer};
api.declare('local.items',items,[]);
const original=read('local.items');
api.append('local.items',2);
assert.equal(read('local.items'),original,'legacy push alias preserved');
assert.throws(()=>api.append('local.items','bad'),{code:'VALUE_TYPE_MISMATCH'});
assert.equal(JSON.stringify(original),'[2]','bad append must not mutate');
assert.throws(()=>write('local.items',['bad']),{code:'VALUE_TYPE_MISMATCH'});
assert.throws(()=>api.declare('local.items',{type:'array',items:{type:'string'}},[]),{code:'TYPE_REDECLARATION'});
const compiled=scope.compileWriteScopePath('local.items',env);
assert.throws(()=>compiled(scopes,'bad'),{code:'VALUE_TYPE_MISMATCH'});
compiled(scopes,[7]);
api.append('local.items',8);
assert.equal(JSON.stringify(read('local.items')),'[7,8]');
api.declare('local.box.typed',items,[]);
assert.throws(()=>write('local.box',{}),{code:'VALUE_TYPE_MISMATCH'});
api.declare('local.map',{type:'object',additionalProperties:integer},{});
api.put('local.map','Paris',18);
assert.throws(()=>api.put('local.map','Paris','bad'),{code:'VALUE_TYPE_MISMATCH'});
assert.equal(read('local.map').Paris,18);
assert.throws(()=>write('local.map.Lyon','bad'),{code:'VALUE_TYPE_MISMATCH'});
for (const key of ['__proto__','constructor','prototype','',1]) assert.throws(()=>api.put('local.map',key,2),{code:'INVALID_MAP_KEY'});
assert.throws(()=>api.declare('input.items',items,[]),{code:'INVALID_DESTINATION'});
assert.throws(()=>api.declare('local.unknown',{type:'array',items:{type:'unknown'}},[]),{code:'UNKNOWN_VALUE_TYPE'});
// Graph execution swaps local scope objects: same path does not share declarations.
const outer=scopes.local;
scopes.local={};
api.declare('local.items',{type:'array',items:{type:'string'}},[]);
api.append('local.items','inner');
scopes.local=outer;
assert.throws(()=>api.append('local.items','inner'),{code:'VALUE_TYPE_MISMATCH'});
assert.ok(!JSON.stringify(scopes).includes('__flowTypeContracts'));
const altered=api.schemaFor('local.items'); altered.items.type='string';
assert.equal(api.schemaFor('local.items').items.type,'integer','callers cannot mutate the declared contract');
console.log('typed-scope-contract: declaration, append/put, compiled writes, replacement, isolation and metadata safety OK');
